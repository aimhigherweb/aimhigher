// Where the tests run, and which pages they cover.
//
// The site under test is always a URL: BASE_URL if it's set (a deploy preview or the live site),
// otherwise the local dev server (`npm run dev`, or the `start` VS Code task for CMS content).
//
// Pages come from the sitemap (when the site was built; the dev server has none), plus anything
// else linked from them or from the home page. Blog posts all share a template, so only a
// sample is tested: the fewest posts that between them include every kind of content (images,
// tables, code, blockquotes…). ALL_POSTS=1 tests every post; PAGES=/,/contact/ tests just those.

import { fileURLToPath } from 'node:url';

export const port = 4321;
export const baseURL = process.env.BASE_URL || `http://localhost:${port}`;

/** Where global setup saves the page list (tests/results is cleared at the start of each run) */
export const cacheFile = fileURLToPath(new URL(`../../results/pages.json`, import.meta.url));
/** A saved list only applies to a run with the same page options */
export const cacheKey = `${process.env.PAGES ?? ``}|${process.env.ALL_POSTS ?? ``}`;

const maxPages = 500;
const concurrency = 6;

/** Links that aren't pages: files, and Vite's dev-only paths */
const notAPage = /\.(png|jpe?g|gif|webp|avif|svg|ico|pdf|zip|xml|txt|json|css|js|mjs|map|woff2?|ttf|mp4|webm|mp3)$/i;
const devPaths = /^\/(@|src\/|node_modules\/|_astro\/)/;

/** `/about` and `/about/` are the same page */
const withSlash = (path) => (path.endsWith(`/`) ? path : `${path}/`);

const isPost = (path) => /^\/blog\/[^/]+\/?$/.test(path);

/** Content a blog post can contain, each needing at least one tested post (a regex or a test function) */
const features = {
	image: /<(img|picture)\b/,
	'figure caption': /<figcaption\b/,
	table: /<table\b/,
	'code block': /<pre\b/,
	// More <code> than <pre> means some code is inline
	'inline code': (body) => (body.match(/<code\b/g)?.length ?? 0) > (body.match(/<pre\b/g)?.length ?? 0),
	blockquote: /<blockquote\b/,
	'bulleted list': /<ul\b/,
	'numbered list': /<ol\b/,
	'subheading (h3+)': /<h[3-6]\b/,
	'embed (iframe/video/audio)': /<(iframe|video|audio)\b/,
	disclosure: /<details\b/,
	'external link': /target="_blank"/,
	'definition list': /<dl\b/,
	abbreviation: /<abbr\b/,
};

/** Only the page body, so the header and footer don't count as post content */
const mainContent = (html) => html.match(/<main\b[^]*<\/main>/)?.[0] ?? html;

const featuresOf = (html) => {
	const body = mainContent(html);

	return Object.entries(features)
		.filter(([, test]) => (typeof test === `function` ? test(body) : test.test(body)))
		.map(([name]) => name);
};

const locs = (xml) => [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map(([, loc]) => loc.trim());

/**
 * Paths listed in the site's sitemap (@astrojs/sitemap). It's only generated by `astro build`,
 * so the dev server has none and this returns [].
 */
export const sitemap = async (base = baseURL) => {
	const get = async (url) => {
		const res = await fetch(new URL(url, base)).catch(() => null);

		return res?.ok && /xml/.test(res.headers.get(`content-type`) ?? ``) ? res.text() : ``;
	};
	const index = await get(`/sitemap-index.xml`);
	const sitemaps = await Promise.all(locs(index).map((loc) => get(new URL(loc).pathname)));

	// The sitemap holds production URLs; keep only the path so they resolve against BASE_URL
	return sitemaps.flatMap(locs).map((loc) => new URL(loc).pathname).map(withSlash);
};

/** Every page in the sitemap or reachable by links from `/`, with the content features of each */
export const crawl = async (base = baseURL) => {
	const origin = new URL(base).origin;
	const queue = [...new Set([`/`, ...await sitemap(base)])];
	const seen = new Set(queue);
	const found = [];

	const visit = async (path) => {
		let res;

		try {
			res = await fetch(new URL(path, base), { redirect: `follow` });
		}
		catch (error) {
			throw new Error(`[a11y] Couldn't reach ${base}: start the dev server (\`start\` VS Code task or \`npm run dev\`) or set BASE_URL`, { cause: error });
		}

		if (!res.ok || !res.headers.get(`content-type`)?.includes(`text/html`)) return;
		// Redirected somewhere else entirely
		if (new URL(res.url).origin !== origin) return;

		const html = await res.text();

		found.push({ path, features: featuresOf(html) });

		for (const [, href] of html.matchAll(/<a\b[^>]*?\shref="([^"#]*)/g)) {
			let url;

			try {
				url = new URL(href.replaceAll(`&amp;`, `&`), new URL(path, base));
			}
			catch {
				continue;
			}

			if (url.origin !== origin || !/^https?:$/.test(url.protocol)) continue;
			if (notAPage.test(url.pathname) || devPaths.test(url.pathname)) continue;

			const next = withSlash(url.pathname);

			if (!seen.has(next) && seen.size < maxPages) {
				seen.add(next);
				queue.push(next);
			}
		}
	};

	while (queue.length) {
		await Promise.all(queue.splice(0, concurrency).map(visit));
	}

	return found.sort((a, b) => a.path.localeCompare(b.path));
};

/** Pick the fewest posts that cover every feature found in any post, and at least `min` posts */
export const samplePosts = (posts, min = 3) => {
	const remaining = posts.map((post) => ({ ...post, has: new Set(post.features) }));
	const uncovered = new Set(remaining.flatMap(({ features: list }) => list));
	const chosen = [];

	while (remaining.length && (uncovered.size || chosen.length < min)) {
		const score = ({ has }) => [...has].filter((name) => uncovered.has(name)).length * 100 + has.size;
		const best = remaining.reduce((a, b) => (score(b) > score(a) ? b : a));

		chosen.push(best);
		remaining.splice(remaining.indexOf(best), 1);
		best.has.forEach((name) => uncovered.delete(name));
	}

	const missing = Object.keys(features).filter((name) => !chosen.some(({ has }) => has.has(name)));

	return { chosen: chosen.map(({ path, features: list }) => ({ path, features: list })), missing };
};

/** The pages to test, and a summary of the blog sample */
export const selectPages = async () => {
	if (process.env.PAGES) {
		return { pages: process.env.PAGES.split(`,`).map((path) => path.trim()).filter(Boolean), summary: [] };
	}

	const all = await crawl();
	const posts = all.filter(({ path }) => isPost(path));

	if (process.env.ALL_POSTS || !posts.length) return { pages: all.map(({ path }) => path), summary: [] };

	const { chosen, missing } = samplePosts(posts);
	const summary = [
		`Testing ${chosen.length} of ${posts.length} blog posts (ALL_POSTS=1 for all):`,
		...chosen.map(({ path, features: list }) => `  ${path}: ${list.join(`, `) || `(plain text)`}`),
		...missing.length ? [`  No post has: ${missing.join(`, `)}`] : [],
	];

	return {
		pages: [...all.filter(({ path }) => !isPost(path)).map(({ path }) => path), ...chosen.map(({ path }) => path)].sort(),
		summary,
	};
};
